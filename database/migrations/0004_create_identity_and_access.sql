-- GreenGrid Solar | Migration 0004
-- Creates identity and authorization structures only. No accounts or permissions are seeded.
-- Permission definitions are business-configurable records and must be created through admin UI.

BEGIN;

CREATE TABLE iam.identity_accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    account_type VARCHAR(30) NOT NULL,
    account_status VARCHAR(30) NOT NULL DEFAULT 'invited',
    login_email VARCHAR(254),
    normalized_login_email VARCHAR(254),
    login_phone VARCHAR(32),
    normalized_login_phone VARCHAR(32),
    email_verified_at TIMESTAMPTZ,
    phone_verified_at TIMESTAMPTZ,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT ck_identity_account_type CHECK (account_type IN ('employee', 'customer', 'service')),
    CONSTRAINT ck_identity_account_status CHECK (account_status IN ('invited', 'active', 'locked', 'disabled', 'pending_recovery'))
);

CREATE UNIQUE INDEX uq_identity_email
    ON iam.identity_accounts(normalized_login_email)
    WHERE normalized_login_email IS NOT NULL;

CREATE UNIQUE INDEX uq_identity_phone
    ON iam.identity_accounts(normalized_login_phone)
    WHERE normalized_login_phone IS NOT NULL;

CREATE TABLE iam.employee_account_links (
    account_id BIGINT PRIMARY KEY REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    employee_id BIGINT NOT NULL UNIQUE REFERENCES org.employees(employee_id) ON DELETE RESTRICT,
    linked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    linked_by_account_id BIGINT REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT
);

CREATE TABLE iam.account_credentials (
    credential_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    credential_type VARCHAR(30) NOT NULL,
    password_hash TEXT,
    secret_reference VARCHAR(240),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ,
    disabled_at TIMESTAMPTZ,
    CONSTRAINT ck_credential_type CHECK (credential_type IN ('password', 'external_identity', 'passkey')),
    CONSTRAINT ck_credential_secret CHECK (
        (credential_type = 'password' AND password_hash IS NOT NULL AND secret_reference IS NULL)
        OR (credential_type <> 'password' AND secret_reference IS NOT NULL AND password_hash IS NULL)
    )
);

CREATE INDEX ix_account_credentials_account ON iam.account_credentials(account_id, disabled_at);

CREATE TABLE iam.sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    account_id BIGINT NOT NULL REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    refresh_token_hash VARCHAR(256) NOT NULL UNIQUE,
    device_label VARCHAR(160),
    source_ip INET,
    user_agent TEXT,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    last_used_at TIMESTAMPTZ,
    CONSTRAINT ck_session_expiry CHECK (expires_at > issued_at)
);

CREATE INDEX ix_sessions_account_active ON iam.sessions(account_id, expires_at) WHERE revoked_at IS NULL;

CREATE TABLE iam.mfa_methods (
    mfa_method_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    method_type VARCHAR(30) NOT NULL,
    secret_reference VARCHAR(240),
    verified_at TIMESTAMPTZ,
    disabled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_mfa_method_type CHECK (method_type IN ('totp', 'webauthn', 'recovery_code'))
);

CREATE TABLE iam.permissions (
    permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    permission_key VARCHAR(160) NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ
);

CREATE TABLE iam.permission_sets (
    permission_set_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    set_name VARCHAR(160) NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ
);

CREATE TABLE iam.permission_set_permissions (
    permission_set_id BIGINT NOT NULL REFERENCES iam.permission_sets(permission_set_id) ON DELETE RESTRICT,
    permission_id BIGINT NOT NULL REFERENCES iam.permissions(permission_id) ON DELETE RESTRICT,
    effect VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (permission_set_id, permission_id),
    CONSTRAINT ck_permission_effect CHECK (effect IN ('allow', 'deny'))
);

CREATE TABLE iam.group_permission_set_grants (
    grant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES org.employee_groups(group_id) ON DELETE RESTRICT,
    permission_set_id BIGINT NOT NULL REFERENCES iam.permission_sets(permission_set_id) ON DELETE RESTRICT,
    scope_type VARCHAR(30) NOT NULL,
    scope_reference VARCHAR(160),
    effect VARCHAR(10) NOT NULL DEFAULT 'allow',
    valid_from TIMESTAMPTZ NOT NULL DEFAULT now(),
    valid_to TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by_account_id BIGINT REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    CONSTRAINT ck_group_grant_scope CHECK (scope_type IN ('own', 'assigned', 'group', 'company', 'resource')),
    CONSTRAINT ck_group_grant_effect CHECK (effect IN ('allow', 'deny')),
    CONSTRAINT ck_group_grant_dates CHECK (valid_to IS NULL OR valid_to > valid_from)
);

CREATE INDEX ix_group_grants_active ON iam.group_permission_set_grants(group_id, valid_to, permission_set_id);

CREATE TABLE iam.account_permission_overrides (
    override_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    permission_id BIGINT NOT NULL REFERENCES iam.permissions(permission_id) ON DELETE RESTRICT,
    scope_type VARCHAR(30) NOT NULL,
    scope_reference VARCHAR(160),
    effect VARCHAR(10) NOT NULL,
    reason TEXT NOT NULL,
    valid_from TIMESTAMPTZ NOT NULL DEFAULT now(),
    valid_to TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by_account_id BIGINT REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    CONSTRAINT ck_account_override_scope CHECK (scope_type IN ('own', 'assigned', 'group', 'company', 'resource')),
    CONSTRAINT ck_account_override_effect CHECK (effect IN ('allow', 'deny')),
    CONSTRAINT ck_account_override_dates CHECK (valid_to IS NULL OR valid_to > valid_from)
);

CREATE INDEX ix_account_overrides_active ON iam.account_permission_overrides(account_id, valid_to, permission_id);

CREATE TABLE iam.invitations (
    invitation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    account_id BIGINT NOT NULL REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    token_hash VARCHAR(256) NOT NULL UNIQUE,
    invited_by_account_id BIGINT REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT ck_invitation_expiry CHECK (expires_at > created_at)
);

CREATE INDEX ix_invitations_account_expiry ON iam.invitations(account_id, expires_at);

COMMIT;
