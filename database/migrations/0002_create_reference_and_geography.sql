BEGIN;

CREATE TABLE ref.reference_sources (
    source_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    source_code VARCHAR(80) NOT NULL UNIQUE,
    source_name VARCHAR(200) NOT NULL,
    source_type VARCHAR(40) NOT NULL,
    terms_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT ck_reference_sources_type CHECK (source_type IN ('government', 'manual', 'licensed_provider', 'internal'))
);

CREATE TABLE ref.reference_import_runs (
    import_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    source_id BIGINT NOT NULL REFERENCES ref.reference_sources(source_id) ON DELETE RESTRICT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    run_status VARCHAR(30) NOT NULL,
    dataset_version VARCHAR(120),
    record_count BIGINT,
    checksum VARCHAR(256),
    error_summary TEXT,
    initiated_by_account_id BIGINT,
    CONSTRAINT ck_reference_import_runs_status CHECK (run_status IN ('queued', 'running', 'completed', 'completed_with_errors', 'failed', 'cancelled')),
    CONSTRAINT ck_reference_import_runs_count CHECK (record_count IS NULL OR record_count >= 0),
    CONSTRAINT ck_reference_import_runs_dates CHECK (completed_at IS NULL OR completed_at >= started_at)
);

CREATE TABLE ref.countries (
    country_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    country_code CHAR(2) NOT NULL,
    country_name VARCHAR(160) NOT NULL,
    normalized_name VARCHAR(160) NOT NULL,
    phone_calling_code VARCHAR(8),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    source_id BIGINT REFERENCES ref.reference_sources(source_id) ON DELETE RESTRICT,
    source_record_key VARCHAR(200),
    last_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_countries_code UNIQUE (country_code),
    CONSTRAINT uq_countries_normalized_name UNIQUE (normalized_name),
    CONSTRAINT ck_countries_code CHECK (country_code ~ '^[A-Z]{2}$')
);

CREATE TABLE ref.states (
    state_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    country_id BIGINT NOT NULL REFERENCES ref.countries(country_id) ON DELETE RESTRICT,
    state_code VARCHAR(30),
    state_name VARCHAR(160) NOT NULL,
    normalized_name VARCHAR(160) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    source_id BIGINT REFERENCES ref.reference_sources(source_id) ON DELETE RESTRICT,
    source_record_key VARCHAR(200),
    last_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_states_country_name UNIQUE (country_id, normalized_name)
);

CREATE TABLE ref.districts (
    district_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    state_id BIGINT NOT NULL REFERENCES ref.states(state_id) ON DELETE RESTRICT,
    district_code VARCHAR(40),
    district_name VARCHAR(160) NOT NULL,
    normalized_name VARCHAR(160) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    source_id BIGINT REFERENCES ref.reference_sources(source_id) ON DELETE RESTRICT,
    source_record_key VARCHAR(200),
    last_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_districts_state_name UNIQUE (state_id, normalized_name)
);

CREATE TABLE ref.local_body_types (
    local_body_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    type_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ
);

CREATE TABLE ref.local_bodies (
    local_body_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    district_id BIGINT NOT NULL REFERENCES ref.districts(district_id) ON DELETE RESTRICT,
    local_body_type_id BIGINT NOT NULL REFERENCES ref.local_body_types(local_body_type_id) ON DELETE RESTRICT,
    local_body_name VARCHAR(180) NOT NULL,
    normalized_name VARCHAR(180) NOT NULL,
    official_code VARCHAR(80),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    source_id BIGINT REFERENCES ref.reference_sources(source_id) ON DELETE RESTRICT,
    source_record_key VARCHAR(200),
    last_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_local_bodies_district_name UNIQUE (district_id, normalized_name)
);

CREATE TABLE ref.postal_codes (
    postal_code_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    country_id BIGINT NOT NULL REFERENCES ref.countries(country_id) ON DELETE RESTRICT,
    postal_code VARCHAR(16) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    source_id BIGINT REFERENCES ref.reference_sources(source_id) ON DELETE RESTRICT,
    source_record_key VARCHAR(200),
    dataset_version VARCHAR(120),
    source_updated_at TIMESTAMPTZ,
    retrieved_at TIMESTAMPTZ,
    last_verified_at TIMESTAMPTZ,
    payload_hash VARCHAR(256),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_postal_codes_country_code UNIQUE (country_id, postal_code)
);

CREATE TABLE ref.post_offices (
    post_office_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    office_name VARCHAR(200) NOT NULL,
    normalized_name VARCHAR(200) NOT NULL,
    office_type VARCHAR(80),
    delivery_status VARCHAR(80),
    district_id BIGINT REFERENCES ref.districts(district_id) ON DELETE RESTRICT,
    state_id BIGINT REFERENCES ref.states(state_id) ON DELETE RESTRICT,
    circle_name VARCHAR(160),
    region_name VARCHAR(160),
    division_name VARCHAR(160),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    source_id BIGINT REFERENCES ref.reference_sources(source_id) ON DELETE RESTRICT,
    source_record_key VARCHAR(200),
    source_updated_at TIMESTAMPTZ,
    retrieved_at TIMESTAMPTZ,
    last_verified_at TIMESTAMPTZ,
    payload_hash VARCHAR(256),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ
);

CREATE TABLE ref.postal_code_post_offices (
    postal_code_id BIGINT NOT NULL REFERENCES ref.postal_codes(postal_code_id) ON DELETE RESTRICT,
    post_office_id BIGINT NOT NULL REFERENCES ref.post_offices(post_office_id) ON DELETE RESTRICT,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (postal_code_id, post_office_id)
);

CREATE TABLE ref.address_types (
    address_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    type_name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ
);

CREATE TABLE ref.units (
    unit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    unit_code VARCHAR(40) NOT NULL UNIQUE,
    unit_name VARCHAR(100) NOT NULL,
    dimension VARCHAR(80) NOT NULL,
    precision_scale SMALLINT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT ck_units_precision CHECK (precision_scale IS NULL OR precision_scale BETWEEN 0 AND 12)
);

CREATE TABLE ref.reference_record_provenance (
    provenance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL REFERENCES ref.reference_sources(source_id) ON DELETE RESTRICT,
    import_run_id BIGINT REFERENCES ref.reference_import_runs(import_run_id) ON DELETE RESTRICT,
    entity_table VARCHAR(160) NOT NULL,
    entity_record_id BIGINT NOT NULL,
    source_record_key VARCHAR(200) NOT NULL,
    source_updated_at TIMESTAMPTZ,
    retrieved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    payload_hash VARCHAR(256),
    CONSTRAINT uq_reference_provenance_source_record UNIQUE (source_id, entity_table, source_record_key)
