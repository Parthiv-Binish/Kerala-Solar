CREATE TABLE org.employees (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    employee_code VARCHAR(80) NOT NULL UNIQUE,
    display_name VARCHAR(180) NOT NULL,
    department_id BIGINT REFERENCES org.departments(department_id) ON DELETE RESTRICT,
    manager_employee_id BIGINT REFERENCES org.employees(employee_id) ON DELETE RESTRICT,
    company_location_id BIGINT REFERENCES org.company_locations(company_location_id) ON DELETE RESTRICT,
    employment_status VARCHAR(40) NOT NULL DEFAULT 'pending',
    work_email VARCHAR(254),
    joined_on DATE,
    left_on DATE,
