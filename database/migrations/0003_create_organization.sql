    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT ck_employee_dates CHECK (left_on IS NULL OR joined_on IS NULL OR left_on >= joined_on),
    CONSTRAINT ck_employee_status CHECK (employment_status IN ('pending', 'active', 'on_leave', 'suspended', 'separated'))
);

CREATE UNIQUE INDEX uq_employees_work_email_normalized
