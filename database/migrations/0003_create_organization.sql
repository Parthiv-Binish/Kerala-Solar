    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT ck_employee_contact_type CHECK (contact_type IN ('phone', 'email', 'other'))
);

CREATE INDEX ix_employee_contacts_employee_active ON org.employee_contacts(employee_id, is_active);
CREATE INDEX ix_employee_contacts_normalized ON org.employee_contacts(contact_type, normalized_value);

