    post_office_id BIGINT REFERENCES ref.post_offices(post_office_id) ON DELETE RESTRICT,
    postal_code_id BIGINT REFERENCES ref.postal_codes(postal_code_id) ON DELETE RESTRICT,
    postal_code_text VARCHAR(16),
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT ck_company_location_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_company_location_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
