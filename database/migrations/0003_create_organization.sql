CREATE TABLE org.company_locations (
    company_location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    location_name VARCHAR(180) NOT NULL,
    location_type VARCHAR(80),
    address_line_1 VARCHAR(240),
    address_line_2 VARCHAR(240),
    place_or_locality VARCHAR(180),
    landmark VARCHAR(180),
    country_id BIGINT REFERENCES ref.countries(country_id) ON DELETE RESTRICT,
    state_id BIGINT REFERENCES ref.states(state_id) ON DELETE RESTRICT,
    district_id BIGINT REFERENCES ref.districts(district_id) ON DELETE RESTRICT,
