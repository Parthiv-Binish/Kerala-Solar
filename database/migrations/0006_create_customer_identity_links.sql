-- Establishes the minimum customer subject model and explicit customer-account links.
-- No customer, contact, account or link records are seeded.
-- This migration does not implement the application authorization resolver.

BEGIN;

CREATE TABLE crm.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    customer_reference VARCHAR(80) NOT NULL UNIQUE,
    customer_kind VARCHAR(40) NOT NULL,
    legal_name VARCHAR(240),
    display_name VARCHAR(240) NOT NULL,
    customer_status VARCHAR(40) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by_account_id BIGINT REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    updated_at TIMESTAMPTZ,
    archived_at TIMESTAMPTZ,
    CONSTRAINT ck_customer_kind CHECK (customer_kind IN ('individual', 'household', 'business', 'other')),
    CONSTRAINT ck_customer_status CHECK (customer_status IN ('active', 'inactive', 'archived'))
);

CREATE TABLE crm.customer_contacts (
    customer_contact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES crm.customers(customer_id) ON DELETE RESTRICT,
    full_name VARCHAR(180) NOT NULL,
    relationship_or_designation VARCHAR(160),
    is_primary_contact BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by_account_id BIGINT REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    archived_at TIMESTAMPTZ,
    CONSTRAINT uq_customer_contact_pair UNIQUE (customer_id, customer_contact_id)
);

CREATE INDEX ix_customer_contacts_customer_active
    ON crm.customer_contacts(customer_id, archived_at);

-- A customer login may be authorised for multiple customer records, and a
-- customer may have multiple authorised logins. Each link is customer-specific.
-- Contact linkage is optional for customer-level authority; when present, the
-- composite FK guarantees that the contact belongs to the linked customer.
CREATE TABLE iam.customer_account_links (
    customer_account_link_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    customer_id BIGINT NOT NULL REFERENCES crm.customers(customer_id) ON DELETE RESTRICT,
    customer_contact_id BIGINT,
    relationship_type VARCHAR(40) NOT NULL,
    link_status VARCHAR(20) NOT NULL DEFAULT 'pending',
    linked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    verified_at TIMESTAMPTZ,
    verified_by_account_id BIGINT REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    revoked_at TIMESTAMPTZ,
    revoked_by_account_id BIGINT REFERENCES iam.identity_accounts(account_id) ON DELETE RESTRICT,
    revocation_reason TEXT,
    CONSTRAINT fk_customer_account_contact
        FOREIGN KEY (customer_id, customer_contact_id)
        REFERENCES crm.customer_contacts(customer_id, customer_contact_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_customer_account_relationship
        CHECK (relationship_type IN ('self', 'owner', 'co_owner', 'family_member', 'legal_representative', 'authorized_contact', 'other')),
    CONSTRAINT ck_customer_account_link_status
        CHECK (link_status IN ('pending', 'active', 'rejected', 'revoked')),
    CONSTRAINT ck_customer_account_verification
        CHECK (
            (link_status <> 'active' OR (verified_at IS NOT NULL AND verified_by_account_id IS NOT NULL))
            AND (link_status <> 'revoked' OR (revoked_at IS NOT NULL AND revoked_by_account_id IS NOT NULL))
        )
);

CREATE UNIQUE INDEX uq_customer_account_link_active
    ON iam.customer_account_links(account_id, customer_id)
    WHERE link_status IN ('pending', 'active');

CREATE UNIQUE INDEX uq_customer_contact_account_active
    ON iam.customer_account_links(customer_id, customer_contact_id, account_id)
    WHERE customer_contact_id IS NOT NULL AND link_status IN ('pending', 'active');

CREATE INDEX ix_customer_account_links_customer
    ON iam.customer_account_links(customer_id, link_status, account_id);

CREATE INDEX ix_customer_account_links_account
    ON iam.customer_account_links(account_id, link_status, customer_id);

-- Customer accounts may not be linked through this table using an employee or
-- service account. A verified link is also required before activation.
CREATE FUNCTION iam.enforce_customer_account_link() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_account_type VARCHAR(30);
    v_actor_type VARCHAR(30);
BEGIN
    SELECT account_type INTO v_account_type
    FROM iam.identity_accounts
    WHERE account_id = NEW.account_id
    FOR KEY SHARE;

    IF v_account_type IS DISTINCT FROM 'customer' THEN
        RAISE EXCEPTION 'customer_account_links requires a customer identity account';
    END IF;

    IF NEW.link_status = 'active' THEN
        IF NEW.verified_at IS NULL OR NEW.verified_by_account_id IS NULL THEN
            RAISE EXCEPTION 'customer account link cannot be active before verification';
        END IF;
        SELECT account_type INTO v_actor_type
        FROM iam.identity_accounts
        WHERE account_id = NEW.verified_by_account_id
        FOR KEY SHARE;
        IF v_actor_type IS DISTINCT FROM 'employee' THEN
            RAISE EXCEPTION 'customer account link must be verified by an employee account';
        END IF;
    END IF;

    IF NEW.link_status = 'revoked' THEN
        IF NEW.revoked_at IS NULL OR NEW.revoked_by_account_id IS NULL THEN
            RAISE EXCEPTION 'revoked customer account link requires actor and timestamp';
        END IF;
        SELECT account_type INTO v_actor_type
        FROM iam.identity_accounts
        WHERE account_id = NEW.revoked_by_account_id
        FOR KEY SHARE;
        IF v_actor_type IS DISTINCT FROM 'employee' THEN
            RAISE EXCEPTION 'customer account link must be revoked by an employee account';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_enforce_customer_account_link
BEFORE INSERT OR UPDATE OF account_id, link_status, verified_at
ON iam.customer_account_links
FOR EACH ROW EXECUTE FUNCTION iam.enforce_customer_account_link();

COMMIT;
